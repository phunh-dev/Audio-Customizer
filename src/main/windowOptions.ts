/**
 * BrowserWindow options: frameless feel with native window controls
 * (titleBarOverlay on Windows/Linux, inset traffic lights on macOS), secure
 * web preferences. Also the title bar theme sync (overlay colours follow the
 * renderer's `html[data-theme]`, reported by the preload over
 * `TITLE_BAR_THEME_EVENT`).
 */
import { join } from 'node:path';
import type { BrowserWindowConstructorOptions, TitleBarOverlayOptions } from 'electron';

export const TITLE_BAR_HEIGHT = 36;

export type TitleBarTheme = 'dark' | 'light';

/** Must match `--color-bg` / `--color-fg` in src/renderer/styles/index.css. */
export const THEME_COLORS: Record<TitleBarTheme, { background: string; symbol: string }> = {
  dark: { background: '#0e1016', symbol: '#e7eaf3' },
  light: { background: '#eef0f5', symbol: '#161a26' },
};

export const WINDOW_BACKGROUND = THEME_COLORS.dark.background;

/**
 * The renderer title bar is dark in both themes (it hosts the logo and tabs),
 * so the native window-controls overlay always uses these colours.
 * Must match `--color-titlebar` in src/renderer/styles/index.css.
 */
export const TITLE_BAR_COLORS = { background: '#0b0d12', symbol: '#e7eaf3' } as const;

export { TITLE_BAR_THEME_EVENT } from './themeChannel';

/** Validate an untrusted theme value from the renderer. */
export function parseTitleBarTheme(v: unknown): TitleBarTheme | null {
  return v === 'dark' || v === 'light' ? v : null;
}

/** Overlay options; identical for both themes because the title bar is always dark. */
export function titleBarOverlay(_theme: TitleBarTheme): TitleBarOverlayOptions {
  return { color: TITLE_BAR_COLORS.background, symbolColor: TITLE_BAR_COLORS.symbol, height: TITLE_BAR_HEIGHT };
}

/** Window / taskbar icon file (generated by `npm run icons` from build/icon.svg). */
export const WINDOW_ICON_FILE = '256x256.png';

export interface IconLocation {
  isPackaged: boolean;
  /** `process.resourcesPath` */
  resourcesPath: string;
  /** `app.getAppPath()` (project root in development) */
  appPath: string;
}

/**
 * dev: <root>/build/icons/256x256.png, packaged: <resources>/icons/256x256.png
 * (copied by electron-builder.yml extraResources; Linux needs it for the
 * window icon, Windows/macOS also embed the icon in the executable / bundle).
 */
export function resolveIconPath(loc: IconLocation): string {
  return loc.isPackaged
    ? join(loc.resourcesPath, 'icons', WINDOW_ICON_FILE)
    : join(loc.appPath, 'build', 'icons', WINDOW_ICON_FILE);
}

export function windowOptions(
  platform: NodeJS.Platform,
  preloadPath: string,
  iconPath?: string,
): BrowserWindowConstructorOptions {
  const opts: BrowserWindowConstructorOptions = {
    width: 1440,
    height: 900,
    minWidth: 960,
    minHeight: 600,
    show: false,
    backgroundColor: WINDOW_BACKGROUND,
    title: 'Audio Customizer',
    titleBarStyle: platform === 'darwin' ? 'hiddenInset' : 'hidden',
    webPreferences: {
      preload: preloadPath,
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
      webSecurity: true,
      spellcheck: false,
    },
  };
  // macOS ignores the window icon (the dock uses the bundle icon / app.dock.setIcon)
  if (iconPath && platform !== 'darwin') opts.icon = iconPath;
  if (platform === 'darwin') {
    opts.trafficLightPosition = { x: 14, y: 11 };
  } else {
    opts.titleBarOverlay = titleBarOverlay('dark');
  }
  return opts;
}

export interface ThemedWindow {
  isDestroyed(): boolean;
  setBackgroundColor(color: string): void;
  setTitleBarOverlay?(options: TitleBarOverlayOptions): void;
}

export interface NativeThemeLike {
  themeSource: 'system' | 'light' | 'dark';
}

/**
 * Apply a renderer theme to the native window: overlay buttons colours
 * (Windows/Linux), window background, and `nativeTheme.themeSource` (native
 * dialogs, macOS window appearance). Invalid values are ignored.
 * Returns the applied theme or null.
 */
export function applyTitleBarTheme(
  win: ThemedWindow | null | undefined,
  platform: NodeJS.Platform,
  value: unknown,
  nativeTheme?: NativeThemeLike,
): TitleBarTheme | null {
  const theme = parseTitleBarTheme(value);
  if (!theme || !win || win.isDestroyed()) return null;
  win.setBackgroundColor(THEME_COLORS[theme].background);
  if (platform !== 'darwin' && typeof win.setTitleBarOverlay === 'function') {
    try {
      win.setTitleBarOverlay(titleBarOverlay(theme));
    } catch {
      // window created without an overlay (should not happen) - colours stay as they are
    }
  }
  if (nativeTheme) nativeTheme.themeSource = theme;
  return theme;
}

/** Only the app itself may be loaded in the window. */
export function isAllowedNavigation(url: string, devServerUrl: string | undefined): boolean {
  if (devServerUrl && url.startsWith(devServerUrl)) return true;
  return url.startsWith('file://');
}
